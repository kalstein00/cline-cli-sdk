test('reviewed raw history failure replay repairs one message without duplicates and distinguishes a new tool question', async () => {
    const record = JSON.parse(await readFile(new URL('../fixtures/history-sync/recovery.json', import.meta.url), 'utf8'));
    const client = createClient({ mode: 'replay' });
    await client.openReplay(record);
    while (client.snapshot().replay.position < record.observations.findIndex(o => o.seq === 19))
        await client.nextObservation();
    const original = client.snapshot();
    assert.equal(original.messages.at(-1).text, 'Last good conversation retained');
    await client.nextObservation();
    assert.equal(client.snapshot().historySync.current, false);
    assert.equal(client.snapshot().interaction.id, original.interaction.id);
    await client.nextObservation();
    assert.equal(client.snapshot().historySync.current, true);
    assert.equal(client.snapshot().messages.at(-1).id, original.messages.at(-1).id);
    assert.equal(client.snapshot().messages.at(-1).text, 'Full requery updated the same message');
    const repaired = client.snapshot();
    await client.nextObservation();
    assert.equal(client.snapshot().revision, repaired.revision);
    await client.replayAll();
    const next = client.snapshot();
    assert.equal(next.interaction.prompt, 'Choose new color.');
    assert.deepEqual(next.interaction.choices, ['GREEN', 'ORANGE']);
    assert.notEqual(next.interaction.id, original.interaction.id);
    assert.equal(next.messages.filter(m => m.id === 'sync-visible-message').length, 1);
    client.close();
});
